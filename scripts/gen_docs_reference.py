def _escape(text: str) -> str:
    """Escapes text for a Markdown table cell or paragraph: pipes and angle brackets (they would start a table cell or an HTML tag)"""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def _code(text: str) -> str:
    """Wraps text in a Markdown code span, using double backticks when the text holds a backtick"""
    return f"`` {text} ``" if "`" in text else f"`{text}`"


def _type_name(annotation: Any) -> str:
    """Name of a type annotation as the docs show it, for example `list[str]` or `Optional[int]`"""
    if isinstance(annotation, type) and typing.get_origin(annotation) is None:  # before Python 3.11, `list[str]` is also an instance of `type`
        return annotation.__name__
    text: str = str(annotation).replace("typing.", "")
    # `X | None` is written `Optional[X]`: a pipe would split the cell of a Markdown table
    return f"Optional[{text.removesuffix(' | None')}]" if text.endswith(" | None") else text


def _toml_value(value: Any) -> str:
    """Spells a Python default the way it is written in TOML. None is "unset" """
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    return str(value)


def parse_attribute_docs(doc: str) -> dict[str, str]:
    """Reads the "Attributes:" section of a Google-style class docstring

    Args:
        doc (str): The docstring

    Returns:
        dict[str, str]: Attribute name to its description (continuation lines joined with a space)
    """
    lines: list[str] = inspect.cleandoc(doc).splitlines()
    descriptions: dict[str, str] = {}
    name: Optional[str] = None
    inside: bool = False

    for line in lines:
        if line.strip() == "Attributes:":
            inside = True
        elif inside and line.strip():
            entry = re.match(r"^ {4}(\w+) \(([^)]*)\): (.*)$", line)
            if entry:
                name = entry.group(1)
                descriptions[name] = entry.group(3).strip()
            elif name is not None and line.startswith(" " * 8):
                descriptions[name] += " " + line.strip()
            else:
                inside = False

    return descriptions


def _without_default(description: str) -> str:
    """Drops a plain "Defaults to X." sentence from a docstring description, because the table has a default column. Longer remarks stay"""
    text: str = re.sub(r"\s*Defaults to (?:\[[^\]]*\]|`[^`]+`|None|False|True)(?=\.?(?:\s|$))\.?", "", description).strip()
    return text if text.endswith(".") else text + "."


def _library_default(field: dataclasses.Field) -> str:
    """The default of a `ScanSettings` field as the docs show it"""
    if field.name in ("exclude_dirs", "exclude_files"):
        return "built-in list"
    if field.default is not dataclasses.MISSING:
        return _toml_value(field.default)
    return _toml_value(field.default_factory())  # type: ignore[misc]


def _cli_default(name: str) -> str:
    """The default of the command line and the config file for a key that has its own"""
    return _toml_value(settings_file.CLI_DEFAULTS[name])


def render_configuration() -> str:
    """Renders `site_src/reference/configuration.md`

    Returns:
        str: The Markdown page
    """
    hints: dict[str, Any] = typing.get_type_hints(ScanSettings)
    descriptions: dict[str, str] = parse_attribute_docs(ScanSettings.__doc__ or "")
    fields: dict[str, dataclasses.Field] = {field.name: field for field in dataclasses.fields(ScanSettings)}

    out: list[str] = [BANNER + CONFIGURATION_INTRO]

    out.append("## Scan options\n")
    out.append(
        'The "CLI default" is what `todonotifier` and the config file use when a key is not set; "same" means it equals the library default. '
        "The library default is what `ScanSettings()` (the Python API) uses.\n"
    )
    out.append("| Key | Type | Library default | CLI default | Description |")
    out.append("|---|---|---|---|---|")
    for key in settings_file.SETTING_KEYS:
        description: str = _without_default(descriptions[key])
        if key in TOML_NOTES:
            description += " " + TOML_NOTES[key]
        cli_default: str = f"`{_cli_default(key)}`" if key in settings_file.CLI_DEFAULTS else "same"
        out.append(f"| `{key}` | `{_type_name(hints[key])}` | `{_library_default(fields[key])}` | {cli_default} | {_escape(description)} |")
    out.append("")

    out.append("### Exclusions\n")
    out.append("`exclude_dirs` and `exclude_files` are tables with these optional lists, all added to the built-in exclusions (case is ignored):\n")
    out.append("| Entry | Meaning |")
    out.append("|---|---|")
    for section in settings_file._EXCLUDE_SECTIONS:
        out.append(f"| `{section}` | {_escape(EXCLUDE_HELP[section])} |")
    out.append("")
    out.append("The built-in directory names are " + ", ".join(f"`{name}`" for name in DEFAULT_EXCLUDE_DIRS["NAME"]) + ".")
    out.append("")
    out.append("The built-in file names are " + ", ".join(f"`{name}`" for name in DEFAULT_EXCLUDE_FILES["NAME"]) + ".")
    out.append("")

    out.append(f"## The `common` extensions\n\n`extensions = \"common\"` expands to: {', '.join(f'`{ext}`' for ext in languages.COMMON_EXTENSIONS)}.\n")

    out.append("## `fail_on`\n")
    out.append(
        f"When the command line exits with 1. The default is `{settings_file.DEFAULT_FAIL_ON}`, and `--fail-on` beats the file. "
        "It does not change which TODOs are found.\n"
    )
    out.append("| Value | Fails when |")
    out.append("|---|---|")
    for choice in settings_file.FAIL_ON_CHOICES:
        out.append(f"| `{choice}` | {_escape(FAIL_ON_HELP[choice])} |")
    out.append("")

    out.append("## `[authors]`\n")
    out.append(
        'Maps git author emails to the handle shown in reports, for example `"ashu@example.com" = "ashu"`. Emails are matched in lower case. '
        "It fills `ScanSettings.author_aliases`.\n"
    )

    out.append("## `[notify.NAME]`\n")
    out.append(
        "Notifiers for `todonotifier notify` (see [Notifications](../notifications.md)). A config file never holds secrets: every key ending in `_env` is "
        "the **name** of an environment variable, and a key such as `webhook`, `url`, `password` or `token` is rejected. Every table also accepts "
        "`enabled` (boolean, default `true`). `NAME` is one of: " + ", ".join(f"`{name}`" for name in settings_file._NOTIFIER_SCHEMA) + ".\n"
    )
    for name, schema in settings_file._NOTIFIER_SCHEMA.items():
        out.append(f"### `[notify.{name}]`\n")
        out.append("| Key | Type | Required | Description |")
        out.append("|---|---|---|---|")
        for key, (kind, required) in schema.items():
            out.append(f"| `{key}` | {NOTIFIER_TYPES[kind]} | {'yes' if required else 'no'} | {_escape(NOTIFIER_HELP[name][key])} |")
        out.append("| `enabled` | boolean | no | Set to `false` to keep the table but skip the notifier. |")
        out.append("")

    return "\n".join(out).rstrip("\n") + "\n"


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, tuple[argparse.ArgumentParser, str]]:
    """The subparsers of `parser` by command name, in the order they were added, each with its one-line help"""
    action: Any = next(item for item in parser._actions if isinstance(item, argparse._SubParsersAction))
    helps: dict[str, str] = {choice.dest: choice.help or "" for choice in action._choices_actions}
    return {name: (command, helps[name]) for name, command in action.choices.items()}


def _flag_row(action: argparse.Action) -> str:
    """One table row for an option: the flags with their metavar, the choices and the help text"""
    options: list[str] = list(action.option_strings)
    if action.metavar:
        options[-1] += f" {action.metavar}"
    elif action.choices:
        options[-1] += " {" + ",".join(str(choice) for choice in action.choices) + "}"
    flags: str = ", ".join(_code(option) for option in options)
    help_text: str = _escape((action.help or "")[:1].upper() + (action.help or "")[1:])
    return f"| {flags} | {help_text} |"


def _options(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    """The options of a parser (not the positional PATH, not -h)"""
    return [action for action in parser._actions if action.option_strings and not isinstance(action, argparse._HelpAction)]


def render_cli() -> str:
    """Renders `site_src/reference/cli.md` from the argparse parser

    Returns:
        str: The Markdown page
    """
    os.environ["COLUMNS"] = "100"  # for the help text of the parser, which does not depend on the width but keeps the result stable if it ever does
    parser: argparse.ArgumentParser = cli.build_parser()
    commands: dict[str, tuple[argparse.ArgumentParser, str]] = _subcommands(parser)

    out: list[str] = [BANNER + "# Command line reference\n"]
    out.append(
        "`todonotifier COMMAND [options]`. `python -m todonotifier` does the same. "
        "For examples and the output formats, see the [command line guide](../cli.md).\n"
    )
    out.append("| Command | What it does |")
    out.append("|---|---|")
    for name, (_, summary) in commands.items():
        out.append(f"| `todonotifier {name}` | {_escape(summary)} |")
    out.append("| `todonotifier --version` | Print the version. |")
    out.append("")

    shared: list[argparse.Action] = [action for action in _options(commands["scan"][0]) if action.dest not in OUTPUT_DESTS]
    shared_flags: set[tuple[str, ...]] = {tuple(action.option_strings) for action in shared}

    out.append("## Flags of `scan`, `report` and `notify`\n")
    out.append("These flags are shared. A flag beats the config file, which beats the built-in defaults. PATH arguments may be mixed with options.\n")
    out.append("| Flag | Meaning |")
    out.append("|---|---|")
    out.append("| `PATH ...` | Files and directories to scan (default: the `paths` of the config file, else `.`). |")
    for action in shared:
        out.append(_flag_row(action))
    out.append("")

    for name, (command, _) in commands.items():
        specific: list[argparse.Action] = [action for action in _options(command) if tuple(action.option_strings) not in shared_flags]
        out.append(f"## `todonotifier {name}`\n")
        out.append(_escape(command.description or "") + "\n")
        if specific:
            out.append("| Flag | Meaning |")
            out.append("|---|---|")
            for action in specific:
                out.append(_flag_row(action))
            out.append("")

    out.append("## Exit codes\n")
    out.append("| Code | Meaning |")
    out.append("|---|---|")
    for code, text in EXIT_CODE_HELP.items():
        out.append(f"| `{code}` | {text} |")
    out.append("")
    out.append(
        "Errors are one line on stderr, for example `todonotifier: error: Unknown key 'tagz' in pyproject.toml [tool.todonotifier]. Did you mean 'tags'?`."
    )

    return "\n".join(out).rstrip("\n") + "\n"


def _markers(markers: tuple[str, ...]) -> str:
    """Code spans of comment markers, or a dash"""
    return ", ".join(_code(marker) for marker in markers) if markers else "-"


def render_languages() -> str:
    """Renders `site_src/reference/_languages.md`, the table of the file types with a known comment syntax

    Returns:
        str: The Markdown table, extensions that share a syntax on one row
    """
    groups: dict[languages.CommentSyntax, list[str]] = {}
    for extension, syntax in languages.COMMENT_SYNTAX.items():
        groups.setdefault(syntax, []).append(extension)

    out: list[str] = [BANNER.rstrip("\n")]
    out.append("")
    out.append("| Extensions | Line comments | Block comments | Multi-line strings | Notes |")
    out.append("|---|---|---|---|---|")
    for syntax, extensions in groups.items():
        notes: list[str] = []
        if syntax.spaced_line_markers:
            notes.append("`#` starts a comment only at the line start or after whitespace")
        if syntax.fenced_code:
            notes.append("fenced code blocks are skipped")
        blocks: str = ", ".join(_code(f"{start} {end}") for start, end in syntax.block_comments) or "-"
        strings: str = ", ".join(_code(delimiter) for delimiter in syntax.multiline_strings) or "-"
        out.append(f"| {', '.join(f'`{ext}`' for ext in extensions)} | {_markers(syntax.line_markers)} | {blocks} | {strings} | {'; '.join(notes)} |")
    out.append("")

    unknown: list[str] = [ext for ext in languages.COMMON_EXTENSIONS if ext not in languages.COMMENT_SYNTAX]
    if unknown:
        out.append(
            "In the `common` preset, these have no known comment syntax, so a tag counts anywhere in them: " + ", ".join(f"`{ext}`" for ext in unknown) + "."
        )
    else:
        out.append("Every extension of the `common` preset has a known comment syntax.")
    return "\n".join(out) + "\n"


def generated_files() -> dict[str, str]:
    """Everything this script generates

    Returns:
        dict[str, str]: Path relative to the repository root to the content it must have
    """
    return {CONFIGURATION_PAGE: render_configuration(), CLI_PAGE: render_cli(), LANGUAGES_PAGE: render_languages()}


def main(argv: Optional[list[str]] = None, root: str = ROOT) -> int:
    """Writes the generated files, or with `--check` compares them with the committed ones

    Args:
        argv (list[str] | None): Command line arguments, default `sys.argv[1:]`
        root (str): Repository root that the paths are relative to

    Returns:
        int: 0 on success, 1 if `--check` found a file that is missing or different
    """
    parser = argparse.ArgumentParser(description="Generate the reference pages of the documentation site from the code.")
    parser.add_argument("--check", action="store_true", help="do not write: exit 1 if a committed file differs from the generated one")
    args: argparse.Namespace = parser.parse_args(argv)

    stale: list[str] = []
    for relative, content in generated_files().items():
        path: str = os.path.join(root, relative)
        if args.check:
            current: Optional[str] = None
            if os.path.exists(path):
                with open(path, encoding="utf-8", newline="") as file:
                    current = file.read()
            if current != content:
                stale.append(relative)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as file:
                file.write(content)
            print(f"wrote {relative}")

    if stale:
        print("These generated files are out of date: " + ", ".join(stale), file=sys.stderr)
        print(f"Run `{REGENERATE_COMMAND}` and commit the result.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
